            <h3 style="color: var(--primary-dark); margin-top: 20px;">1. Preamble</h3>
            <p>Vardhman Finance has adopted this Fair Practices Code to promote good and fair practices in dealing with customers, to ensure transparency in our services, and to build confidence in the company’s integrity.</p>

            <h3 style="color: var(--primary-dark); margin-top: 20px;">2. Applications for Loans and their Processing</h3>
            <ul>
                <li>All communications to the borrower shall be in the vernacular language or a language as understood by the borrower.</li>
                <li>Loan application forms shall include necessary information which affects the interest of the borrower, so that a meaningful comparison with the terms and conditions offered by other NBFCs can be made and informed decision can be taken by the borrower.</li>
                <li>The Company shall devise a system of giving acknowledgement for receipt of all loan applications.</li>
            </ul>

            <h3 style="color: var(--primary-dark); margin-top: 20px;">3. Loan Appraisal and Terms/Conditions</h3>
            <ul>
                <li>The Company shall convey in writing to the borrower in the vernacular language or a language as understood by the borrower by means of sanction letter or otherwise, the amount of loan sanctioned along with the terms and conditions including annualized rate of interest and method of application thereof and keep the acceptance of these terms and conditions by the borrower on its record.</li>
                <li>The Company shall furnish a copy of the loan agreement as understood by the borrower along with a copy each of all enclosures quoted in the loan agreement to all the borrowers at the time of sanction / disbursement of loans.</li>
            </ul>

            <h3 style="color: var(--primary-dark); margin-top: 20px;">4. Disbursement of Loans Including Changes in Terms and Conditions</h3>
            <ul>
                <li>The Company shall give notice to the borrower in the vernacular language or a language as understood by the borrower of any change in the terms and conditions including disbursement schedule, interest rates, service charges, prepayment charges etc.</li>
                <li>Decision to recall / accelerate payment or performance under the agreement shall be in consonance with the loan agreement.</li>
            </ul>

            <h3 style="color: var(--primary-dark); margin-top: 20px;">5. General</h3>
            <ul>
                <li>The Company shall refrain from interference in the affairs of the borrower except for the purposes provided in the terms and conditions of the loan agreement (unless information, not earlier disclosed by the borrower, has been noticed).</li>
                <li>In case of receipt of request from the borrower for transfer of borrowal account, the consent or otherwise i.e. objection of the Company, if any, shall be conveyed within 21 days from the date of receipt of request.</li>
                <li>In the matter of recovery of loans, the Company shall not resort to undue harassment viz; persistently bothering the borrowers at odd hours, use of muscle power for recovery of loans etc.</li>
            </ul>

            <h3 style="color: var(--primary-dark); margin-top: 20px;">6. Grievance Redressal Mechanism</h3>
            <p>The Company has a grievance redressal mechanism to resolve disputes arising in this regard. The Board of Directors shall also provide for periodical review of the compliance of the Fair Practices Code and the functioning of the grievances redressal mechanism at various levels of management.</p>

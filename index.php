document.addEventListener('DOMContentLoaded', function () {
    const revealNodes = document.querySelectorAll('.scroll-reveal, .loan-card, .cta-card, .review-card, .contact-card');
    revealNodes.forEach((node) => node.classList.add('scroll-reveal'));
    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.15 });
    revealNodes.forEach((node) => observer.observe(node));

    const counterObserver = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (!entry.isIntersecting) return;
            const el = entry.target;
            const target = parseInt(el.getAttribute('data-counter'), 10) || 0;
            let current = 0;
            const step = Math.max(1, Math.ceil(target / 35));
            const timer = setInterval(() => {
                current += step;
                if (current >= target) {
                    current = target;
                    clearInterval(timer);
                }
                el.textContent = current.toLocaleString();
            }, 28);
            counterObserver.unobserve(el);
        });
    }, { threshold: 0.45 });
    document.querySelectorAll('[data-counter]').forEach((counter) => counterObserver.observe(counter));

    const laneObserver = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (!entry.isIntersecting) return;
            const fill = entry.target;
            fill.style.width = fill.dataset.fill || '0%';
            laneObserver.unobserve(fill);
        });
    }, { threshold: 0.5 });
    document.querySelectorAll('.lane-fill').forEach((fill) => laneObserver.observe(fill));
});
